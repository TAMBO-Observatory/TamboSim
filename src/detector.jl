# Geometry constants
"""Height factor for triangular grid spacing (ratio of row height to column spacing)."""
const TRIANGULAR_GRID_HEIGHT_FACTOR = sqrt(3) / 2

"""Default detection module dimensions [length, width, height] in meters."""
const DEFAULT_MODULE_EXTENT_M = SVector{3}([1.875, 0.8, 0.03])

"""
    SquareDetectionModule

Represents a square-shaped detection module.

# Fields
- `pos::SVector{3, Float64}`: The center position of the module.
- `rot::Rotation`: The rotation of the module in space.
- `extent::SVector{3, Float64}`: The side lengths of the module (x, y, z).
- `idx::Int`: An index to identify the module.
"""
struct SquareDetectionModule
  pos::SVector{3, Float64}
  rot::Rotation
  extent::SVector{3, Float64}
  idx::Int
end

"""
    CircularDetectionModule

Represents a circular-shaped detection module.

# Fields
- `pos::SVector{3, Float64}`: The center position of the module.
- `rot::Rotation`: The rotation of the module in space.
- `extent::SVector{2, Float64}`: The radius and height of the module.
- `idx::Int`: An index to identify the module.
"""
struct CircularDetectionModule
  pos::SVector{3, Float64}
  rot::Rotation
  extent::SVector{2, Float64}
  idx::Int
end

DetectionModule = Union{SquareDetectionModule, CircularDetectionModule}

