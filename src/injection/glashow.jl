# Glashow-resonance injection: ν̄_e + e⁻ → W⁻ → τ⁻ ν̄_τ.
#
# The τ⁻ is produced at a forced vertex within its decay range of the detector, exactly
# like the τ branch of `force_interaction_vertex`. Unlike `inject_neutrinos!`, the ν̄_e is
# not propagated with TauRunner (which has no Glashow process). Its attenuation from
# Earth entry to the vertex is carried in the weight instead (see `GlashowInteractionPoint`).

# PDG 2024 values.
const GLASHOW_MW     = 80.3692    # GeV
const GLASHOW_GAMMAW = 2.085      # GeV
const GLASHOW_GF     = 1.1663788e-5  # GeV⁻²
const GLASHOW_ME     = 0.51099895e-3 # GeV
const GLASHOW_MTAU   = 1.77686    # GeV, same as particle_parameters[TauMinus]
const GLASHOW_HBARC2 = 0.3893793721e-27  # cm² GeV², converts GeV⁻² to cm²

# Tree-level partial width Γ(W → ℓν) for a massless lepton. Using it (rather than the
# measured BR) keeps σ_total = σ_ℓ / BR(W→ℓν) consistent with the Breit-Wigner below,
# so the peak is exactly 24π·BR(W→eν)/M_W².
const GLASHOW_GAMMA_LNU = GLASHOW_GF * GLASHOW_MW^3 / (6 * sqrt(2) * π)  # GeV
const GLASHOW_BR_LNU    = GLASHOW_GAMMA_LNU / GLASHOW_GAMMAW

"""
    glashow_sigma_lepton_tree(E, m_lepton) -> Quantity{cm²}

Tree-level cross section for ν̄_e e⁻ → W⁻ → ℓ⁻ ν̄_ℓ on an electron at rest, with
s = 2 m_e E:

    σ_ℓ(s) = G_F² M_W⁴/(3π) · s (1 − m_ℓ²/s)² (1 + m_ℓ²/2s) / [(s − M_W²)² + M_W² Γ_W²]

`E` is the ν̄_e energy and `m_lepton` the charged-lepton mass in GeV.
"""
function glashow_sigma_lepton_tree(E::Quantity, m_lepton::Real)
    s = 2 * GLASHOW_ME * ustrip(u"GeV", E)
    r = m_lepton^2 / s
    r >= 1 && return 0.0u"cm^2"
    mw2 = GLASHOW_MW^2
    σ = GLASHOW_GF^2 * mw2^2 / (3π) * s * (1 - r)^2 * (1 + r / 2) /
        ((s - mw2)^2 + mw2 * GLASHOW_GAMMAW^2)
    return σ * GLASHOW_HBARC2 * u"cm^2"
end

"""
    GlashowCrossSection(; corrections=false, location=nothing)

Glashow-resonance cross sections for ν̄_e on electrons at rest.

With `corrections=false` everything is tree level. With `corrections=true` the tree-level
total and τ-channel cross sections are multiplied by ratios (Doppler broadening from
atomic-electron motion and initial-state radiation) read from the HDF5 group named in
`location`, e.g. `"cross_sections.h5:GR_nuebar"`. The group holds `energies` (GeV),
`ratio_total` and `ratio_tau`, generated by
`resources/cross_section_tables/scripts/make_glashow_table.jl`.

The τ energy distribution is always dσ_τ/dy = σ_τ · 3(1 − y)² with y = E_τ/E. The
m_τ²/s ≈ 3e-7 correction to the shape is dropped.
"""
struct GlashowCrossSection
    corrections :: Bool
    ratio_total :: Union{Spline1D, Nothing}
    ratio_tau   :: Union{Spline1D, Nothing}
    emin        :: Quantity{Float64, edim, typeof(u"GeV")}
    emax        :: Quantity{Float64, edim, typeof(u"GeV")}
end

function GlashowCrossSection(; corrections::Bool=false, location=nothing)
    if !corrections
        return GlashowCrossSection(false, nothing, nothing, 0.0u"GeV", Inf * u"GeV")
    end
    isnothing(location) && error(
        "GlashowCrossSection: corrections=true needs `location` (\"file.h5:GR_nuebar\")."
    )
    filename, groupname = split(location, ":")
    es, rtot, rtau = h5open(filename) do file
        group = file[groupname]
        read(group["energies"]), read(group["ratio_total"]), read(group["ratio_tau"])
    end
    tot = Spline1D(log.(es), rtot; k=1)
    tau = Spline1D(log.(es), rtau; k=1)
    return GlashowCrossSection(true, tot, tau, minimum(es) * u"GeV", maximum(es) * u"GeV")
end

function _glashow_ratio(spl::Union{Spline1D, Nothing}, xs::GlashowCrossSection, E::Quantity)
    isnothing(spl) && return 1.0
    xs.emin <= E <= xs.emax || throw(ArgumentError(
        "Energy $(E) outside the Glashow correction table range [$(xs.emin), $(xs.emax)]"
    ))
    return spl(log(ustrip(u"GeV", E)))
end

"""
    glashow_sigma_total(xs::GlashowCrossSection, E) -> Quantity{cm²}

Total ν̄_e e⁻ → W⁻ cross section (all W⁻ decay channels). Used for ν̄_e absorption.
"""
function glashow_sigma_total(xs::GlashowCrossSection, E::Quantity)
    tree = glashow_sigma_lepton_tree(E, 0.0) / GLASHOW_BR_LNU
    return tree * _glashow_ratio(xs.ratio_total, xs, E)
end

"""
    glashow_sigma_tau(xs::GlashowCrossSection, E) -> Quantity{cm²}

Cross section for ν̄_e e⁻ → W⁻ → τ⁻ ν̄_τ.
"""
function glashow_sigma_tau(xs::GlashowCrossSection, E::Quantity)
    tree = glashow_sigma_lepton_tree(E, GLASHOW_MTAU)
    return tree * _glashow_ratio(xs.ratio_tau, xs, E)
end

"""
    glashow_dsigma_tau_dEtau(xs::GlashowCrossSection, E, Etau) -> Quantity{cm²/GeV}

dσ_τ/dE_τ = σ_τ · 3(1 − y)² / E with y = E_τ/E.
"""
function glashow_dsigma_tau_dEtau(xs::GlashowCrossSection, E::Quantity, Etau::Quantity)
    y = Etau / E
    0 <= y <= 1 || return 0.0u"cm^2/GeV"
    return glashow_sigma_tau(xs, E) * 3 * (1 - y)^2 / uconvert(u"GeV", E)
end

"""
    sample_y_glashow() -> Float64

Draw y = E_τ/E from 3(1 − y)² on [0, 1].
"""
sample_y_glashow() = 1 - cbrt(rand())

"""
Internal implementation of a single Glashow-resonance event.

Returns `(initial_state, final_state, point)`. `initial_state` is the ν̄_e at the Earth
entry point. `final_state` is the τ⁻ at the forced vertex. `point` is a
`GlashowInteractionPoint`, or `nothing` on failure.
"""
function _inject_glashow_event_impl(
    pdg::Int,
    prem,
    bvh::BVHTree{T},
    cs::CoordinateSystem{T},
    detector_region,
    as::UniformAngularSampler,
    pl::UnitfulPowerLawSampler,
    gxs::GlashowCrossSection,
    dis_xs::CrossSection,
    detector_props::DetectorProperties{T},
    epsilon,
) where {T<:Real}
    d = rand(as, cs)

    p, visible_areas = sample_detector_point(
        detector_props.triangles, detector_props.normals, detector_props.areas,
        detector_props.bvh, d, cs, epsilon
    )
    if isnothing(p)
        null = _create_null_neutrino_result(pdg, INJECTION_ERROR_NO_VISIBLE_TRIANGLES, d, cs, T)
        return null[1], null[3], nothing
    end

    revd = reverse(d)
    intersections, error_code = validate_earth_trajectory(prem, bvh, detector_region, p, revd)
    if isnothing(intersections)
        null = _create_null_neutrino_result(pdg, error_code, d, cs, T)
        return null[1], null[3], nothing
    end

    initial_energy = rand(pl)
    earth_entry = last(intersections).point
    initial_state = Particle(ParticleType(pdg), initial_energy, earth_entry, d)

    local final_state, point
    try
        etau = sample_y_glashow() * initial_energy
        range = particle_vacuum_range(TauMinus, etau)
        distance, cd_cap, density, cd_to_vertex = _find_vertex_distance_by_distance(
            revd, range, intersections
        )
        # Column the ν̄_e crossed before reaching the vertex (Earth entry → vertex).
        x_up = max(total_column_depth(intersections, revd) - cd_to_vertex, 0.0u"g/cm^2")

        pout = Coordinate(first(intersections).point.point + revd.point * distance, cs)
        final_state = Particle(TauMinus, etau, pout, d)

        theta, phi = cart_to_sph(d)
        point = GlashowInteractionPoint(
            initial_energy, etau, theta, phi, sum(visible_areas),
            density |> u"g/cm^3", cd_cap |> u"g/cm^2", x_up |> u"g/cm^2",
            glashow_sigma_tau(gxs, initial_energy) |> u"cm^2",
            glashow_sigma_total(gxs, initial_energy) |> u"cm^2",
            dis_xs(initial_energy) |> u"cm^2",
        )
    catch e
        @warn "Runtime error during Glashow injection, returning null result" exception=(e, catch_backtrace())
        null = _create_null_neutrino_result(pdg, INJECTION_ERROR_RUNTIME, d, cs, T)
        return null[1], null[3], nothing
    end

    return initial_state, final_state, point
end

"""
    inject_glashow!(frames::TamboFrames, config::Dict; prefix::String="injection")

Inject ν̄_e Glashow-resonance events (ν̄_e e⁻ → W⁻ → τ⁻ ν̄_τ). Mutates `frames` by
appending one M frame (config snapshot under `prefix`) and `config["nevent"]` Q frames.
Each successful Q frame carries:

- `<prefix>_initial_state` — the ν̄_e at the Earth entry point, energy from the power law.
- `<prefix>_final_state`   — the τ⁻ at the forced vertex, E_τ = yE with y ~ 3(1 − y)².
- `phase_space_point`      — a `GlashowInteractionPoint` for `oneweight` / `oneweights`.

The vertex is placed uniformly in column depth within the τ vacuum decay range of the
detector, as for ν_τ CC. There is no TauRunner step. The ν̄_e survival from Earth entry
to the vertex, exp(−X[n_e σ_GR + n_N σ_DIS]), goes into the weight. σ_DIS is the CC
total of the table at `config["xs_location"]` (CSMS_nutau, a proxy for ν̄_e by lepton
universality). NC is not included: over a ~10 km rock chord it changes the survival
by < 1%.

# Config keys
Same as `inject_neutrinos!` (`pdg` must be -12), plus the optional
`glashow_corrections` (Bool, default `false`). When `true`, the Doppler + ISR correction
ratios are read from group `GR_nuebar` of the same HDF5 file as `xs_location`.
"""
function inject_glashow!(
    frames::TamboFrames,
    config::Dict;
    prefix::String="injection"
)
    Int(config["pdg"]) == Int(NuEBar) || error(
        "inject_glashow!: GlashowInjection requires pdg = -12 (ν̄_e), got $(config["pdg"])."
    )
    g_frame, m_frame, q_frames = _setup_injection(frames, config, prefix, "inject_glashow!")
    d_frame = m_frame.d_frame

    prem            = g_frame["prem"]
    bvh             = g_frame["bvh"]
    cs              = g_frame["cs"]
    detector_region = d_frame["detector_region"]
    detector_bvh    = d_frame["detector_bvh"]

    pl = UnitfulPowerLawSampler(
        config["gamma"],
        config["emin"] * u"GeV",
        config["emax"] * u"GeV"
    )
    as = UniformAngularSampler(
        deg2rad(config["thetamin"]),
        deg2rad(config["thetamax"]),
        deg2rad(config["phimin"]),
        deg2rad(config["phimax"]),
    )
    dis_xs = CrossSection(config["xs_location"])
    corrections = get(config, "glashow_corrections", false)
    gxs = if corrections
        h5file = first(split(config["xs_location"], ":"))
        GlashowCrossSection(; corrections=true, location="$(h5file):GR_nuebar")
    else
        GlashowCrossSection()
    end
    # Same detector surface as inject_neutrinos!, so ν̄_e and ν_τ acceptances compare directly.
    detector_triangles = detector_bvh.triangles
    detector_props = DetectorProperties(
        detector_triangles, normal.(detector_triangles), detector_bvh, area.(detector_triangles)
    )
    Random.seed!(config["seed"])

    @llama_showprogress "Injecting Glashow ν̄_e" for frame in q_frames
        istate, fstate, point = _inject_glashow_event_impl(
            Int(config["pdg"]), prem, bvh, cs, detector_region,
            as, pl, gxs, dis_xs, detector_props, 1e-6 * u"m",
        )
        frame["$(prefix)_initial_state"] = istate
        if !isnan(fstate.energy)
            frame["$(prefix)_final_state"] = fstate
        end
        point === nothing || (frame["phase_space_point"] = point)
    end
end
